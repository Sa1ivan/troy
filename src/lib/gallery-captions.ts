export function galleryPhotoCaption(src: string): string | undefined {
  const match = /^\/images\/(.+)\/(\d+)\.webp$/.exec(src);
  if (!match) return undefined;
  const [, folder, number] = match;
  return captions[folder]?.[Number(number) - 1];
}
